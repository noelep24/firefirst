// Writes src/api/schema-version.ts: a fingerprint of the backend's API schema. The phone's saved data cache is
// keyed by it, so data saved by an older version of the API is discarded instead of crashing newer screens.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const schema = readFileSync(new URL('../../backend/openapi.yml', import.meta.url));
const version = createHash('sha256').update(schema).digest('hex').slice(0, 12);
writeFileSync(
  new URL('../src/api/schema-version.ts', import.meta.url),
  `// Generated by scripts/schema-version.mjs (npm run api:types). Do not edit.\nexport const SCHEMA_VERSION = '${version}';\n`,
);
